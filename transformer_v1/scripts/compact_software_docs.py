def compact_manual_cover(doc: Document) -> None:
    """Keep the contractor line on the cover instead of spilling to its own page."""
    paragraphs = doc.paragraphs
    page_index = next(i for i, p in enumerate(paragraphs) if p.text.strip() == "共XX页")
    contractor_index = next(
        i for i, p in enumerate(paragraphs) if p.text.strip() == "承担单位：华东理工大学"
    )
    blanks = [p for p in paragraphs[page_index + 1 : contractor_index] if not p.text.strip()]
    for paragraph in blanks[:-4]:
        paragraph._element.getparent().remove(paragraph._element)


