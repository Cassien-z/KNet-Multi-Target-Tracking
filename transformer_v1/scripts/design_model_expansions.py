Block = tuple


def _semantic_title(text: str) -> str:
    text = re.sub(r"^\d+(?:\.\d+)*\s*", "", text)
    text = re.sub(r"^附录\s*[A-Z](?:\.\d+)*\s*", "", text)
    return text.strip()


def _section_prefix(heading_text: str) -> str:
    match = re.match(r"^(\d+(?:\.\d+)*)\s", heading_text)
    if match:
        return match.group(1)
    match = re.match(r"^(附录\s*[A-Z])(?:\s|$)", heading_text)
    if match:
        return match.group(1)
    return ""


def _cohesive_blocks(heading_text: str, blocks: list[Block]) -> list[Block]:
    """Collapse heading-plus-one-paragraph fragments into connected prose.

    A third-level heading is retained only when it organizes a table, list, or
    at least two narrative paragraphs.  Consecutive short prose fragments are
    paired in one paragraph and introduced by bold lead-ins.  Retained third-
    level headings are renumbered within their parent section so the outline
    remains continuous after the reduction.
    """

    segments: list[tuple[Block | None, list[Block]]] = []
    pending: list[Block] = []
    current_heading: Block | None = None
    for block in blocks:
        if block[0] == "h3":
            if current_heading is not None or pending:
                segments.append((current_heading, pending))
            current_heading = block
            pending = []
        else:
            pending.append(block)
    if current_heading is not None or pending:
        segments.append((current_heading, pending))

    prefix = _section_prefix(heading_text)
    retained_index = 0
    normalized: list[Block] = []
    for heading, content in segments:
        if heading is None:
            normalized.extend(content)
            continue
        title = _semantic_title(heading[1])
        if len(content) == 1 and content[0][0] == "p":
            normalized.append(("lead", title, content[0][1]))
            continue
        retained_index += 1
        numbered_title = f"{prefix}.{retained_index} {title}" if prefix else title
        normalized.append(("h3", numbered_title))
        normalized.extend(content)

    cohesive: list[Block] = []
    lead_group: list[tuple[str, str]] = []
    lead_chars = 0

    def flush_leads() -> None:
        nonlocal lead_group, lead_chars
        if lead_group:
            cohesive.append(("lead_group", lead_group))
            lead_group = []
            lead_chars = 0

    for block in normalized:
        if block[0] != "lead":
            flush_leads()
            cohesive.append(block)
            continue
        item_chars = len(block[1]) + len(block[2])
        if lead_group and (len(lead_group) >= 2 or lead_chars + item_chars > 420):
            flush_leads()
        lead_group.append((block[1], block[2]))
        lead_chars += item_chars
    flush_leads()
    return cohesive


def _write_blocks(doc: Document, heading_text: str, blocks: list[Block]) -> None:
    for block in _cohesive_blocks(heading_text, blocks):
        kind = block[0]
        if kind == "h3":
            doc.add_heading(block[1], level=3)
        elif kind == "lead_group":
            paragraph = doc.add_paragraph()
            for index, (lead, text) in enumerate(block[1]):
                if index:
                    paragraph.add_run(" ")
                paragraph.add_run(f"{lead}：").bold = True
                paragraph.add_run(text)
        elif kind == "p":
            doc.add_paragraph(block[1])
        elif kind == "bullets":
            add_bullets(doc, block[1])
        elif kind == "steps":
            add_numbered_steps(doc, block[1])
        elif kind == "table":
            add_table(doc, block[1], block[2], widths=block[3])
        else:
            raise ValueError(f"Unknown expansion block: {kind}")


def _append_to_section(doc: Document, heading_text: str, writer: Callable[[Document], None]) -> None:
    body = doc._element.body
    target = None
    target_level = None
    for child in body:
        if child.tag != qn("w:p"):
            continue
        paragraph = Paragraph(child, doc._body)
        if paragraph.text.strip() != heading_text:
            continue
        style = paragraph.style.name if paragraph.style is not None else ""
        if not style.startswith("Heading "):
            continue
        target = child
        target_level = int(style.split()[-1])
        break
    if target is None or target_level is None:
        raise RuntimeError(f"Cannot find expansion target: {heading_text}")

    stop = body.sectPr
    sibling = target.getnext()
    while sibling is not None and sibling is not body.sectPr:
        if sibling.tag == qn("w:p"):
            paragraph = Paragraph(sibling, doc._body)
            style = paragraph.style.name if paragraph.style is not None else ""
            if style.startswith("Heading ") and int(style.split()[-1]) <= target_level:
                stop = sibling
                break
        sibling = sibling.getnext()

    append_index = body.index(body.sectPr)
    writer(doc)
    new_children = list(body)[append_index : body.index(body.sectPr)]
    for child in new_children:
        stop.addprevious(child)


